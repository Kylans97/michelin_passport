#!/usr/bin/env python3
"""Turns the source checks of the wine atlas's style text into one SQL
update (product owner, 2026-11-20: "can you search online for style? Use
multiple source").

    python3 -I build_style_update.py

Reads the four reviews next to it (europe_regions, americas_regions,
grapes_classic, grapes_new; the .md files hold every field, verdict and
source, the .json only what changes) and writes wine_style_update_v1.sql.
Every change there rests on at least two sources from different
organisations, listed in the matching .md; fields the checks supported
are left as they are. The nine Dutch region summaries come from their
BOB dossiers and were not part of this check; their grapes were.
"""

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
REVIEWS = ['europe_regions', 'americas_regions', 'grapes_classic',
           'grapes_new']
TEXT_ARRAYS = {'tastes', 'aliases'}


def lit(value, field):
    if value is None:
        return 'null'
    if field in TEXT_ARRAYS:
        items = ','.join('"' + v.replace('"', '\\"') + '"' for v in value)
        return quote('{' + items + '}') + '::text[]'
    if isinstance(value, (int, float)):
        return str(value)
    return quote(value)


def quote(text):
    return "'" + str(text).replace("'", "''") + "'"


def statement(r):
    t, k, f, p = r['table'], r['key'], r['field'], r['proposed']
    if t == 'wine_regions':
        return (f'update public.wine_regions set {f} = {lit(p, f)} '
                f"where region_code = '{k['region_code']}';")
    if t == 'wine_appellations':
        return (f'update public.wine_appellations set {f} = {lit(p, f)} '
                f"where appellation_code = '{k['appellation_code']}';")
    if t == 'grapes' and f == 'similar':
        if p is None:
            return ('update public.grapes set similar_grape_id = null, '
                    f"similar_note = null where grape_code = '{k['grape_code']}';")
        return ('update public.grapes g set similar_grape_id = s.id, '
                f"similar_note = {quote(p['note'])} from public.grapes s "
                f"where s.grape_code = '{p['grape_code']}' "
                f"and g.grape_code = '{k['grape_code']}';")
    if t == 'grapes':
        return (f'update public.grapes set {f} = {lit(p, f)} '
                f"where grape_code = '{k['grape_code']}';")
    region, grape = k['region_code'], k['grape_code']
    link = ('(select id from public.wine_regions where region_code = '
            f"'{region}'), (select id from public.grapes where grape_code = "
            f"'{grape}')")
    where = ('region_id = (select id from public.wine_regions where '
             f"region_code = '{region}') and grape_id = (select id from "
             f"public.grapes where grape_code = '{grape}')")
    if f == 'link' and p == 'remove':
        return f'delete from public.wine_region_grapes where {where};'
    if f == 'link' and p == 'add':
        return ('insert into public.wine_region_grapes (region_id, grape_id, '
                f"local_note, display_order) values ({link}, "
                f"{lit(r.get('local_note'), 'local_note')}, "
                f"{r.get('display_order') or 0});")
    return (f'update public.wine_region_grapes set {f} = {lit(p, f)} '
            f'where {where};')


def main():
    out = ['-- Generated by build_style_update.py from the four source checks',
           '-- in this folder. Every change cites two or more sources from',
           '-- different organisations in the matching .md file.',
           '', 'begin;']
    total = 0
    for name in REVIEWS:
        rows = json.load(open(HERE / f'{name}.json', encoding='utf-8'))
        out += ['', f'-- {name}: {len(rows)} changes ({name}.md)']
        for r in rows:
            out.append(statement(r))
        total += len(rows)
    out += ['', 'commit;', '']
    (HERE / 'wine_style_update_v1.sql').write_text('\n'.join(out),
                                                   encoding='utf-8')
    print(f'{total} changes written')


if __name__ == '__main__':
    main()
