#!/usr/bin/env python3
"""Write fill-only SQL for one country's Place ID / phone / website gaps.

Usage: python3 build_gap_fill_sql.py <CC> <decisions.csv> <out.sql> <export_date>

decisions.csv is the reviewed per-row research for that country (columns
kind, code, name, place_id, phone, website, place_status, phone_status,
website_status, ...). Only values marked confirmed are written, and only
into empty fields. Every row is guarded by code + name + country, so a file
can never land on a different restaurant or hotel that took the same code.
"""
import csv, sys

CC, F, OUT, DATE = sys.argv[1:5]
R = list(csv.DictReader(open(F)))


def q(v):
    return 'NULL' if v is None or v == '' else "'" + str(v).replace("'", "''") + "'"


blocks = []
for kind, table, codecol in (('restaurant', 'restaurants', 'restaurant_code'), ('hotel', 'hotels', 'hotel_code')):
    rows = [r for r in R if r['kind'] == kind and (r['place_id'] or r['phone'] or r['website'])]
    if not rows:
        continue
    t = f'_fill_{kind}'
    vals = ',\n'.join(f"    ({q(r['code'])}, {q(r['name'])}, {q(r['place_id'])}, {q(r['phone'])}, {q(r['website'])})" for r in rows)
    blocks.append(f"""-- {table}: {len(rows)} rows ({sum(1 for r in rows if r['place_id'])} Place IDs, {sum(1 for r in rows if r['phone'])} phones, {sum(1 for r in rows if r['website'])} websites)
create temp table {t} (code text primary key, name text not null, place_id text unique, phone text, website text) on commit drop;
insert into {t} values
{vals};

do $$
declare bad text;
begin
  -- identity: each code must still be the {CC} row of that name
  select string_agg(f.code, ', ') into bad from {t} f
   where not exists (select 1 from public.{table} x where x.{codecol} = f.code and x.name = f.name and x.country_code = '{CC}');
  if bad is not null then raise exception '{table}: code is no longer the exported {CC} row: %', bad; end if;
  -- Place IDs are unique per table
  select string_agg(f.code || ' -> ' || f.place_id || ' (held by ' || x.{codecol} || ')', '; ') into bad
    from {t} f join public.{table} x on x.google_place_id = f.place_id and x.{codecol} <> f.code;
  if bad is not null then raise exception '{table}: Place ID already used by another row: %', bad; end if;
end $$;

update public.{table} x set google_place_id = f.place_id, updated_at = now()
  from {t} f where x.{codecol} = f.code and f.place_id is not null and x.google_place_id is null;
update public.{table} x set phone = f.phone, updated_at = now()
  from {t} f where x.{codecol} = f.code and f.phone is not null and x.phone is null;
update public.{table} x set website_url = f.website, updated_at = now()
  from {t} f where x.{codecol} = f.code and f.website is not null and x.website_url is null;""")

head = f"""-- PREPARED -- NOT APPLIED.
--
-- {CC}: fill missing Google Place IDs, phone numbers and websites
-- (export of {DATE}). Generated by europe_gaps/build_gap_fill_sql.py from the
-- reviewed research in the matching *_gap_fill.csv (evidence and the reason
-- per row, including every value held back).
--
-- Fill-only: a value is written only where the field is NULL; nothing is
-- overwritten. Place ID: the venue's own Google record (restaurant, or
-- lodging for a hotel), within 100 m of the stored point, or 100-500 m with
-- the official domain; never a hotel's record for a named restaurant inside
-- it. Phone: MICHELIN and Google agreeing, or the number printed on the
-- official site. Website: MICHELIN's link and the Google record agreeing on
-- the domain, or a site that loads and names the restaurant.
--
-- One transaction; any failed check rolls the whole file back. Safe to
-- re-run (fill-only).

begin;
"""
open(OUT, 'w').write(head + '\n\n'.join(blocks) + '\n\ncommit;\n')
print('written', OUT)
