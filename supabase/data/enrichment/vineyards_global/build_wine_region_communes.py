"""Write prepared_wine_region_communes.sql from the repo's commune lists.

One row per distinct unit per region, from
supabase/data/enrichment/wine_regions/outlines/communes/wr_NNNN.csv. A unit
listed more than once in a region (a Portuguese union of parishes under
each of its old names, for example) becomes one row under the unit's own
name (lau_name), partial when any of its lines is. Keyed on region_code
and the unit id, never on a name. Centre points stay NULL here.

Run from the repo root:
    python3 -I supabase/data/enrichment/vineyards_global/build_wine_region_communes.py
"""
import csv
import glob
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'wine_regions', 'outlines', 'communes')
OUT = os.path.join(HERE, 'prepared_wine_region_communes.sql')


def q(v):
    return 'null' if v is None or v == '' else "'" + v.replace("'", "''") + "'"


def main():
    units = {}
    for path in sorted(glob.glob(os.path.join(SRC, 'wr_*.csv'))):
        for r in csv.DictReader(open(path, encoding='utf-8')):
            key = (r['region_code'], r['gisco_id'])
            u = units.setdefault(key, {'name': r['lau_name'], 'province': r['province'], 'partial': False})
            if r['lau_name'] != u['name']:
                raise SystemExit(f'{key}: two unit names {u["name"]!r} / {r["lau_name"]!r}')
            u['partial'] = u['partial'] or bool(r['partial'].strip())
    regions = sorted({k[0] for k in units})
    rows = ',\n'.join(
        f"  ({q(rc)}, {q(cc)}, {q(u['name'])}, {q(u['province'])}, {'true' if u['partial'] else 'false'})"
        for (rc, cc), u in sorted(units.items()))
    sql = f"""-- The units each wine region's official text is built from, loaded
-- into public.wine_region_communes (migration 20261101740000).
-- Generated by build_wine_region_communes.py from
-- wine_regions/outlines/communes/: {len(units)} units in {len(regions)} regions.
-- PREPARED -- review before applying.
-- Stops as a whole if a region code is missing or the count is off.

begin;

with src(region_code, commune_code, name, province, is_partial) as (values
{rows}
)
insert into public.wine_region_communes (region_id, commune_code, name, province, is_partial)
select r.id, s.commune_code, s.name, s.province, s.is_partial
from src s
join public.wine_regions r on r.region_code = s.region_code
on conflict (region_id, commune_code) do nothing;

do $$
begin
  if (select count(*) from public.wine_region_communes) <> {len(units)} then
    raise exception 'expected {len(units)} wine_region_communes rows, stopping';
  end if;
end $$;

commit;
"""
    open(OUT, 'w', encoding='utf-8').write(sql)
    print(len(units), 'units in', len(regions), 'regions;', sum(u['partial'] for u in units.values()), 'partial')


if __name__ == '__main__':
    main()
