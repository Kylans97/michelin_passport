#!/usr/bin/env python3
"""Write the migration and prepared_europe9_2026.sql from the reviewed control files.

  python3 build_sql.py

Reads controle/<CC>.csv and _source/production_export_20261104.json, so the SQL holds
exactly what the product owner reviewed (2026-11-04). The decisions on the seven held-back
rows, the edition year and the town spelling are the proposals in README.md, accepted that day.
"""
import collections, csv, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
MIG_DIR = os.path.normpath(os.path.join(HERE, '../../../migrations'))
MIGRATION = '20261101300000_add_europe9_2026_countries_and_cities.sql'
CCS = ['CZ', 'HR', 'SI', 'HU', 'MT', 'LT', 'LV', 'EE', 'RS']
COUNTRIES = [('CZ', 'Czechia', '🇨🇿', 'Europe/Prague'), ('EE', 'Estonia', '🇪🇪', 'Europe/Tallinn'),
             ('LT', 'Lithuania', '🇱🇹', 'Europe/Vilnius'), ('LV', 'Latvia', '🇱🇻', 'Europe/Riga')]
IN_PLACE = {'hotel_277'}                                     # QA-451, QA-384 shape
CHANGED = {'hotel_260', 'hotel_267', 'hotel_280'}            # QA-452, QA-454, QA-383 shape
LOST = {'hotel_301', 'hotel_305'}                            # QA-453, QA-387 shape
PLATAN = 'rest_0427'                                         # QA-450
KEY_ANNOUNCED = '2026-09-18'
CC_LIST = ', '.join(f"'{c}'" for c in CCS)


def q(v):
    return 'NULL' if v is None or v == '' else "'" + str(v).replace("'", "''") + "'"


def main():
    R = []
    for cc in CCS:
        R += list(csv.DictReader(open(os.path.join(HERE, 'controle', f'{cc}.csv'))))
    X = json.load(open(os.path.join(HERE, '_source', 'production_export_20261104.json')))
    newr = [r for r in R if r['kind'] == 'restaurant' and r['action'] == 'new']
    newh = [r for r in R if r['kind'] == 'hotel' and r['action'] == 'new']
    held = {r['code']: r for r in R if r['action'] == 'HELD BACK'}
    assert set(held) == IN_PLACE | CHANGED | LOST | {PLATAN}
    fills_r = [r for r in R if r['kind'] == 'restaurant' and r['proposed_fill']]
    fills_h = [r for r in R if r['kind'] == 'hotel' and r['proposed_fill']]
    assert all(r['proposed_fill'] == 'michelin_url' for r in fills_r + fills_h)
    links = [r for r in R if r['kind'] == 'restaurant' and r['hotel_code'] and r['action'] != 'HELD BACK']
    towns = sorted({(r['country'], r['town']) for r in R if r['town_is_new'] == 'new'})
    live = [r for r in R if r['award'] != '']

    # ================= migration =================
    mig = f"""-- MICHELIN CZ, HR, SI, HU, MT, LT, LV, EE, RS: country and city prerequisite for
-- supabase/data/enrichment/michelin_europe9_2026/prepared_europe9_2026.sql.
-- Written 2026-11-04 by build_sql.py from production's read-only export of that day.
-- Filename timestamp is a sequence number only (next after 20261101290000, Greece's slot,
-- which is not applied yet: apply that first, or use `supabase db push --include-all` for it).
-- Production has no `countries` row for CZ, EE, LT or LV (export 2026-11-04). Each zone is
-- present in production's pg_timezone_names (read 2026-11-04). Czechia is MICHELIN's own name.
-- Restaurant towns are MICHELIN's English listing names, hotel towns the hotel page's locality,
-- with MICHELIN's spelling kept by the product owner's decision of 2026-11-04 (QA-458). None
-- exists in production's export, compared accent- and case-insensitively. region and
-- postal_municipality NULL, as the existing rows.
-- Idempotent: ON CONFLICT targets countries_pkey and cities_unique_key.

begin;

insert into public.countries (country_code, name, flag_emoji, timezones)
values
""" + ',\n'.join(f"  ({q(c)}, {q(n)}, {q(f)}, array[{q(z)}])" for c, n, f, z in COUNTRIES) + """
on conflict (country_code) do nothing;

insert into public.cities (country_code, name, region)
values
""" + ',\n'.join(f"  ({q(c)}, {q(t)}, NULL)" for c, t in towns) + """
on conflict (country_code, name, coalesce(region, '')) do nothing;

commit;
"""
    open(os.path.join(MIG_DIR, MIGRATION), 'w').write(mig)

    # ================= prepared SQL =================
    stored = X['restaurants'] + X['hotels']
    S = [f"""-- PREPARED -- NOT APPLIED.
--
-- MICHELIN's live selection for CZ, HR, SI, HU, MT, LT, LV, EE and RS, read 2026-11-04.
-- Generated by build_sql.py from controle/<CC>.csv; evidence per row there and in match_report.csv.
-- Reviewed by the product owner on 2026-11-04, who accepted the proposals in README.md.
--
-- Restaurants: {len(newr)} added ({newr[0]['code']}..{newr[-1]['code']}); {PLATAN} Platán Gourmet closed, stars NULL (QA-450).
-- Hotels: {len(newh)} Key hotels added ({newh[0]['code']}..{newh[-1]['code']}); hotel_277 corrected in place (QA-451);
--   hotel_280, hotel_260, hotel_267 changed in 2026 (QA-452, QA-454); hotel_301, hotel_305 lost their Key (QA-453).
-- Filled, only where empty: michelin_url on {len(fills_r)} restaurants and {len(fills_h)} hotels.
-- Links: {len(links)}; property_name: {sum(1 for r in newr if r['property_name'])}.
-- No Google Place ID is written (no Google access in this pass, QA-457).
--
-- PREREQUISITE: supabase/migrations/{MIGRATION}.
-- One transaction; every check raises and rolls the whole file back.
-- Run: supabase db query --linked -f <absolute path to this file>

begin;

-- 0. production is still the export of {X['exported_at'][:16]} UTC
do $$
declare n int;
begin
  select count(*) into n from public.restaurants where country_code in ({CC_LIST});
  if n <> {len(X['restaurants'])} then raise exception 'expected {len(X['restaurants'])} restaurants (export), found % -- production changed or this file has run', n; end if;
  select count(*) into n from public.hotels where country_code in ({CC_LIST});
  if n <> {len(X['hotels'])} then raise exception 'expected {len(X['hotels'])} hotels (export), found % -- production changed or this file has run', n; end if;
  select count(*) into n from (values {', '.join(f"({q(e['code'])}, {q(e['name'])}, {q(e['country'])})" for e in stored)}) e(code, name, cc)
   where not exists (select 1 from public.restaurants r where r.restaurant_code = e.code and r.name = e.name and r.country_code = e.cc)
     and not exists (select 1 from public.hotels h where h.hotel_code = e.code and h.name = e.name and h.country_code = e.cc);
  if n <> 0 then raise exception '% exported codes no longer carry their exported name', n; end if;
  if exists (select 1 from public.restaurants where restaurant_code = any(array[{', '.join(q(r['code']) for r in newr)}]))
  then raise exception 'restaurant codes {newr[0]['code']}..{newr[-1]['code']} are no longer free'; end if;
  if exists (select 1 from public.hotels where hotel_code = any(array[{', '.join(q(r['code']) for r in newh)}]))
  then raise exception 'hotel codes {newh[0]['code']}..{newh[-1]['code']} are no longer free'; end if;
  select count(*) into n from public.countries where country_code in ({CC_LIST});
  if n <> 9 then raise exception 'found % of 9 countries (run the migration first?)', n; end if;
end $$;"""]

    def rows_for(codes):
        return [held[c] for c in sorted(codes)]

    S.append(f"""-- 1. QA-451 Párisi Udvar: stored 2 Keys match no edition (MICHELIN 1 in 2025 and 2026). In place, QA-384 shape;
--    no 2025 value is asserted.
do $$
declare n int;
begin
  select count(*) into n from public.hotels h
    join public.award_history a on a.entity_type = 'hotel' and a.entity_id = h.id and a.award_type = 'michelin_keys'
   where h.hotel_code = 'hotel_277' and h.michelin_keys = 2 and a.is_current and a.guide_year = 2026 and a.award_value = 2 and a.announced_on is null;
  if n <> 1 then raise exception 'hotel_277: launch row not found as exported'; end if;
end $$;
update public.award_history a set award_value = 1
  from public.hotels h
 where h.hotel_code = 'hotel_277' and a.entity_type = 'hotel' and a.entity_id = h.id and a.award_type = 'michelin_keys'
   and a.is_current and a.guide_year = 2026 and a.award_value = 2;
update public.hotels set michelin_keys = 1, updated_at = now() where hotel_code = 'hotel_277' and michelin_keys = 2;""")

    S.append(f"""-- 2. Key changes and losses in 2026: the launch row (labelled 2026, announced_on NULL) holds MICHELIN's 2025 Key
--    (MICHELIN's listings archived 16, 17 and 22 Oct 2025). Relabelled 2025 and closed; a current 2026 row written.
--    QA-452 Bristol, QA-454 Villa Dubrovnik and Palace Elisabeth (QA-383 shape); QA-453 Peterc and Nebesa stay with NULL (QA-387).
create temp table _kchg (code text primary key, was smallint, keys smallint) on commit drop;
insert into _kchg values
{(',' + chr(10)).join(f"    ({q(r['code'])}, {r['stored_award']}, {r['award'] or 'NULL'})" for r in rows_for(CHANGED | LOST))};
do $$
declare n int;
begin
  select count(*) into n from _kchg k join public.hotels h on h.hotel_code = k.code and h.michelin_keys = k.was
    join public.award_history a on a.entity_type = 'hotel' and a.entity_id = h.id and a.award_type = 'michelin_keys'
   where a.is_current and a.guide_year = 2026 and a.award_value = k.was and a.announced_on is null;
  if n <> {len(CHANGED | LOST)} then raise exception '% of {len(CHANGED | LOST)} Key launch rows found as exported', n; end if;
  select count(*) into n from _kchg k join public.hotels h on h.hotel_code = k.code
    join public.award_history a on a.entity_type = 'hotel' and a.entity_id = h.id and a.award_type = 'michelin_keys' and a.guide_year = 2025;
  if n <> 0 then raise exception '% hotels already have a 2025 Key row', n; end if;
end $$;
update public.award_history a set guide_year = 2025, is_current = false
  from _kchg k, public.hotels h
 where h.hotel_code = k.code and a.entity_type = 'hotel' and a.entity_id = h.id and a.award_type = 'michelin_keys'
   and a.is_current and a.guide_year = 2026 and a.announced_on is null and a.award_value = k.was;
insert into public.award_history (entity_type, entity_id, guide_year, award_type, award_value, is_current, announced_on)
select 'hotel', h.id, 2026, 'michelin_keys', k.keys, true, date '{KEY_ANNOUNCED}'
  from _kchg k join public.hotels h on h.hotel_code = k.code;
update public.hotels h set michelin_keys = k.keys, updated_at = now()
  from _kchg k where h.hotel_code = k.code and h.michelin_keys = k.was;""")

    S.append(f"""-- 3. Key hotels missing from the catalogue, each with a current 2026 Key row. Name = page h1; address and pin =
--    page JSON-LD. Phone, website and Place ID NULL: none confirmable outside MICHELIN in this pass (QA-457).
create temp table _newh (code text, cc text, name text, keys smallint, city text, address text, lon float8, lat float8,
                        michelin_url text) on commit drop;
insert into _newh values
{(',' + chr(10)).join(f"    ({q(r['code'])}, {q(r['country'])}, {q(r['name'])}, {r['award']}, {q(r['town'])}, {q(r['address'])}, {r['lon']}, {r['lat']}, {q(r['michelin_url'])})" for r in newh)};
do $$
declare bad text;
begin
  select string_agg(x.name || ' (' || x.city || ')', ', ') into bad from _newh x
   where (select count(*) from public.cities c where c.country_code = x.cc and c.name = x.city) <> 1;
  if bad is not null then raise exception 'city does not resolve to exactly one row (run the migration first?): %', bad; end if;
  select string_agg(x.name, ', ') into bad from _newh x join public.hotels h
    on substring(h.michelin_url from '-([0-9]+)/?$') = substring(x.michelin_url from '-([0-9]+)/?$');
  if bad is not null then raise exception 'hotel already present (MICHELIN id): %', bad; end if;
end $$;
insert into public.hotels (hotel_code, name, michelin_keys, city_id, country_code, address, location, michelin_url)
select x.code, x.name, x.keys,
       (select c.id from public.cities c where c.country_code = x.cc and c.name = x.city), x.cc,
       x.address, ST_SetSRID(ST_MakePoint(x.lon, x.lat), 4326)::geography, x.michelin_url
  from _newh x;
insert into public.award_history (entity_type, entity_id, guide_year, award_type, award_value, is_current, announced_on)
select 'hotel', h.id, 2026, 'michelin_keys', h.michelin_keys, true, date '{KEY_ANNOUNCED}'
  from public.hotels h join _newh x on x.code = h.hotel_code;""")

    S.append(f"""-- 4. QA-450 Platán Gourmet: stopped trading (its own site, read 2026-11-04; date unknown, so status_since NULL), off
--    MICHELIN's list, page 404. The row stays for visits and the Passport; its link to hotel_268 stays. The launch row holds
--    the 2025 edition's 2 stars (article of 9 Oct 2025): relabelled 2025 and closed. The current row is NULL with
--    announced_on NULL: MICHELIN announced no loss, and no date is invented.
do $$
declare n int;
begin
  select count(*) into n from public.restaurants r
    join public.award_history a on a.entity_type = 'restaurant' and a.entity_id = r.id and a.award_type = 'michelin_stars'
   where r.restaurant_code = '{PLATAN}' and r.michelin_stars = 2 and r.status = 'open' and a.is_current and a.guide_year = 2026 and a.award_value = 2;
  if n <> 1 then raise exception '{PLATAN}: not found as exported'; end if;
end $$;
update public.award_history a set guide_year = 2025, is_current = false
  from public.restaurants r
 where r.restaurant_code = '{PLATAN}' and a.entity_type = 'restaurant' and a.entity_id = r.id and a.award_type = 'michelin_stars'
   and a.is_current and a.guide_year = 2026 and a.award_value = 2;
insert into public.award_history (entity_type, entity_id, guide_year, award_type, award_value, is_current, announced_on)
select 'restaurant', r.id, 2026, 'michelin_stars', NULL, true, NULL from public.restaurants r where r.restaurant_code = '{PLATAN}';
update public.restaurants set michelin_stars = NULL, status = 'permanently_closed',
       status_note = 'Stopped trading, per the venue''s own site read 2026-11-04; date not stated. QA-450.', updated_at = now()
 where restaurant_code = '{PLATAN}' and michelin_stars = 2;""")

    S.append(f"""-- 5. starred restaurants missing from the catalogue, each with a current row. guide_year = the page's dateAwarded
--    (Hungary 2025, the others 2026; QA-455), announced_on = MICHELIN's edition article.
create temp table _newr (code text, cc text, name text, stars smallint, city text, address text, lon float8, lat float8,
                        michelin_url text, website_url text, phone text, property_name text, guide_year smallint, announced date) on commit drop;
insert into _newr values
{(',' + chr(10)).join(f"    ({q(r['code'])}, {q(r['country'])}, {q(r['name'])}, {r['award']}, {q(r['town'])}, {q(r['address'])}, {r['lon']}, {r['lat']}, {q(r['michelin_url'])}, {q(r['website'])}, {q(r['phone'])}, {q(r['property_name'])}, {r['guide_year']}, date '{r['announced_on']}')" for r in newr)};
do $$
declare bad text;
begin
  select string_agg(x.name || ' (' || x.city || ')', ', ') into bad from _newr x
   where (select count(*) from public.cities c where c.country_code = x.cc and c.name = x.city) <> 1;
  if bad is not null then raise exception 'city does not resolve to exactly one row (run the migration first?): %', bad; end if;
  select string_agg(x.name, ', ') into bad from _newr x join public.restaurants r on r.michelin_url = x.michelin_url;
  if bad is not null then raise exception 'already present (michelin_url): %', bad; end if;
end $$;
insert into public.restaurants (restaurant_code, name, michelin_stars, inclusion_reason, city_id, country_code,
                                address, location, michelin_url, website_url, phone, property_name)
select x.code, x.name, x.stars, 'michelin_star',
       (select c.id from public.cities c where c.country_code = x.cc and c.name = x.city), x.cc,
       x.address, ST_SetSRID(ST_MakePoint(x.lon, x.lat), 4326)::geography,
       x.michelin_url, x.website_url, x.phone, x.property_name
  from _newr x;
insert into public.award_history (entity_type, entity_id, guide_year, award_type, award_value, is_current, announced_on)
select 'restaurant', r.id, x.guide_year, 'michelin_stars', x.stars, true, x.announced
  from _newr x join public.restaurants r on r.restaurant_code = x.code;""")

    S.append(f"""-- 6. michelin_url filled on existing rows, only where empty; identity per row in controle/<CC>.csv.
create temp table _urlr (code text primary key, url text) on commit drop;
insert into _urlr values
{(',' + chr(10)).join(f"    ({q(r['code'])}, {q(r['michelin_url'])})" for r in fills_r)};
create temp table _urlh (code text primary key, url text) on commit drop;
insert into _urlh values
{(',' + chr(10)).join(f"    ({q(r['code'])}, {q(r['michelin_url'])})" for r in fills_h)};
do $$
declare n int;
begin
  select count(*) into n from _urlr u join public.restaurants r on r.restaurant_code = u.code and r.michelin_url is null;
  if n <> {len(fills_r)} then raise exception '% of {len(fills_r)} restaurants have an empty michelin_url', n; end if;
  select count(*) into n from _urlh u join public.hotels h on h.hotel_code = u.code and h.michelin_url is null;
  if n <> {len(fills_h)} then raise exception '% of {len(fills_h)} hotels have an empty michelin_url', n; end if;
  if exists (select 1 from _urlr u join public.restaurants r on r.michelin_url = u.url)
     or exists (select 1 from _urlh u join public.hotels h on h.michelin_url = u.url) then
    raise exception 'a MICHELIN url is already used by another row'; end if;
end $$;
update public.restaurants r set michelin_url = u.url, updated_at = now() from _urlr u where r.restaurant_code = u.code and r.michelin_url is null;
update public.hotels h set michelin_url = u.url, updated_at = now() from _urlh u where h.hotel_code = u.code and h.michelin_url is null;""")

    S.append(f"""-- 7. links to hotels in `hotels`, each where MICHELIN's review names the hotel (evidence column; QA-459)
create temp table _links (hotel_code text, restaurant_code text, confidence text, evidence text) on commit drop;
insert into _links values
{(',' + chr(10)).join(f"    ({q(r['hotel_code'])}, {q(r['code'])}, 'exact', {q(r['note'] + ' 2026-11-04.')})" for r in links)};
do $$
declare n int;
begin
  select count(*) into n from _links l join public.hotels h on h.hotel_code = l.hotel_code
    join public.restaurants r on r.restaurant_code = l.restaurant_code
   where r.property_name is null;
  if n <> {len(links)} then raise exception 'links: % of {len(links)} hotel/restaurant pairs resolve', n; end if;
end $$;
insert into public.hotel_restaurants (hotel_id, restaurant_id, link_confidence, evidence, verified_at)
select h.id, r.id, l.confidence, l.evidence, now()
  from _links l join public.hotels h on h.hotel_code = l.hotel_code join public.restaurants r on r.restaurant_code = l.restaurant_code
on conflict (hotel_id, restaurant_id) do nothing;""")

    post = []
    for cc in CCS:
        st = collections.Counter(int(r['award']) for r in live if r['country'] == cc and r['kind'] == 'restaurant')
        ke = collections.Counter(int(r['award']) for r in live if r['country'] == cc and r['kind'] == 'hotel')
        for k in (3, 2, 1):
            post.append(f"""  select count(*) into n from public.restaurants where country_code = '{cc}' and michelin_stars = {k};
  if n <> {st[k]} then raise exception '{cc}: expected {st[k]} {k}-star, found %', n; end if;""")
        for k in (3, 2, 1):
            post.append(f"""  select count(*) into n from public.hotels where country_code = '{cc}' and michelin_keys = {k};
  if n <> {ke[k]} then raise exception '{cc}: expected {ke[k]} {k}-Key hotels, found %', n; end if;""")
    S.append(f"""-- 8. post-conditions: MICHELIN's live selection exactly
do $$
declare n int;
begin
""" + '\n'.join(post) + f"""
  select count(*) into n from public.restaurants r where r.country_code in ({CC_LIST})
     and (select count(*) from public.award_history ah where ah.entity_type = 'restaurant' and ah.entity_id = r.id
           and ah.award_type = 'michelin_stars' and ah.is_current and ah.award_value is not distinct from r.michelin_stars) <> 1;
  if n <> 0 then raise exception '% restaurants without exactly one current star row equal to michelin_stars', n; end if;
  select count(*) into n from public.hotels h where h.country_code in ({CC_LIST})
     and (select count(*) from public.award_history a where a.entity_type = 'hotel' and a.entity_id = h.id
           and a.award_type = 'michelin_keys' and a.is_current and a.award_value is not distinct from h.michelin_keys) <> 1;
  if n <> 0 then raise exception '% hotels without exactly one current Key row equal to michelin_keys', n; end if;
  select count(*) into n from public.hotels h join public.award_history a on a.entity_type = 'hotel' and a.entity_id = h.id
   where h.hotel_code in ('hotel_260', 'hotel_267', 'hotel_280', 'hotel_301', 'hotel_305')
     and a.award_type = 'michelin_keys' and a.guide_year = 2025 and not a.is_current and a.award_value is not null;
  if n <> 5 then raise exception '% of 5 hotels kept their 2025 Key as history', n; end if;
  select count(*) into n from public.restaurants r join public.award_history a on a.entity_type = 'restaurant' and a.entity_id = r.id
   where r.restaurant_code = '{PLATAN}' and r.status = 'permanently_closed' and a.award_type = 'michelin_stars'
     and a.guide_year = 2025 and a.award_value = 2 and not a.is_current;
  if n <> 1 then raise exception '{PLATAN} did not keep its 2 stars as history'; end if;
  select count(*) into n from public.restaurants r where r.country_code in ({CC_LIST}) and r.property_name is not null
     and exists (select 1 from public.hotel_restaurants hr where hr.restaurant_id = r.id);
  if n <> 0 then raise exception '% restaurants have both a hotel link and a property_name', n; end if;
  select count(*) into n from public.restaurants where country_code in ({CC_LIST});
  if n <> {len(X['restaurants']) + len(newr)} then raise exception 'expected {len(X['restaurants']) + len(newr)} restaurants, found %', n; end if;
  select count(*) into n from public.hotels where country_code in ({CC_LIST});
  if n <> {len(X['hotels']) + len(newh)} then raise exception 'expected {len(X['hotels']) + len(newh)} hotels, found %', n; end if;
end $$;

commit;
""")
    open(os.path.join(HERE, 'prepared_europe9_2026.sql'), 'w').write('\n\n'.join(S))
    print('new', len(newr), len(newh), 'fills', len(fills_r), len(fills_h), 'links', len(links), 'towns', len(towns))


if __name__ == '__main__':
    main()
